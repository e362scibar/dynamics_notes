"""Load the document numbers of the topics and check the repository against them.

``common/documents.toml`` is the single source of truth for the document numbers (``YYYY-NNN``). This module
reads it, allocates the next number, renders the BibTeX database ``common/documents.bib`` so that documents can
be cited with ``\\cite{<number>}``, and checks that topics, LaTeX sources, notebooks, and citations agree with the
registry.

Usage (from the repository root)::

    python common/python/dynamics_common/documents.py              # check the repository
    python common/python/dynamics_common/documents.py --write      # regenerate common/documents.bib
    python common/python/dynamics_common/documents.py --number curvilinear_coordinates
    python common/python/dynamics_common/documents.py --next       # next free number of this year
"""

import argparse
import datetime
import re
import sys
import tomllib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCUMENTS_PATH = REPO_ROOT / "common" / "documents.toml"
DOCUMENTS_BIB_PATH = REPO_ROOT / "common" / "documents.bib"
TOPICS_DIR = REPO_ROOT / "topics"
LATEX_FILE_NAME = "main.tex"

NUMBER_PATTERN = re.compile(r"^(?P<year>\d{4})-(?P<serial>\d{3})$")
SERIAL_DIGITS = 3
MAX_SERIAL = 999
SLUG_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")
STATUS_ACTIVE = "active"
STATUS_WITHDRAWN = "withdrawn"
VALID_STATUSES = (STATUS_ACTIVE, STATUS_WITHDRAWN)
DEFAULT_AUTHOR = "Maesaka, Hirokazu"
INSTITUTION = "RIKEN SPring-8 Center"
BIB_TYPE_LABEL = "Memo"
LATEX_COMMENT_PREFIX = "%"
LATEX_NUMBER_MACRO_PATTERN = re.compile(r"\\setmemonumber\{([^}]*)\}")
LATEX_CITE_PATTERN = re.compile(r"\\[A-Za-z]*cite[A-Za-z]*\*?(?:\[[^\]]*\]){0,2}\{([^}]*)\}")
NOTEBOOK_CITE_PATTERN = re.compile(r"\[(\d{4}-\d{3})(?:,[^\]]*)?\]")
BIB_HEADER = """% common/documents.bib
% Generated from common/documents.toml by `python common/python/dynamics_common/documents.py --write`.
% Do not edit this file by hand; edit documents.toml and regenerate.
% Cite a document with \\cite{<number>} in LaTeX and [<number>] in notebook markdown cells and comments.
%
% Copyright (C) 2026 Hirokazu Maesaka (RIKEN SPring-8 Center)
% SPDX-License-Identifier: CC-BY-4.0
"""

__all__ = [
    "DOCUMENTS_BIB_PATH",
    "DOCUMENTS_PATH",
    "Document",
    "check_repository",
    "find_latex_citations",
    "find_notebook_citations",
    "format_number",
    "load_documents",
    "next_number",
    "number_for_topic",
    "render_bibtex",
]


@dataclass(frozen=True)
class Document:
    """One registered document.

    Attributes:
        number: Document number ``YYYY-NNN``, the table name in ``documents.toml``.
        slug: Directory name under ``topics/``. Empty for a withdrawn document without a directory.
        title: English title.
        status: ``active`` or ``withdrawn``.
        author: BibTeX author.
        note: Free text.
    """

    number: str
    slug: str
    title: str
    status: str = STATUS_ACTIVE
    author: str = DEFAULT_AUTHOR
    note: str = ""


def format_number(year: int, serial: int) -> str:
    """Format a document number.

    Args:
        year: Four-digit year.
        serial: Serial number within the year, 1 to 999.

    Returns:
        The number ``YYYY-NNN``.

    Raises:
        ValueError: If the serial number is out of range.
    """
    if not 1 <= serial <= MAX_SERIAL:
        raise ValueError(f"Serial number {serial} is out of range 1 to {MAX_SERIAL}.")
    return f"{year:04d}-{serial:0{SERIAL_DIGITS}d}"


def _require_string(number: str, table: dict[str, object], field: str, required: bool, default: str = "") -> str:
    """Read a string field of one document table.

    Args:
        number: Document number, used in error messages.
        table: Parsed table.
        field: Field name.
        required: Whether the field must be present and non-empty.
        default: Value used when an optional field is absent.

    Returns:
        The field value.

    Raises:
        ValueError: If the field has the wrong type or a required field is empty.
    """
    value = table.get(field, default)
    if not isinstance(value, str):
        raise ValueError(f"Document '{number}' has an invalid '{field}'; expected a string.")
    if required and not value:
        raise ValueError(f"Document '{number}' must define a non-empty '{field}'.")
    return value


def _parse_document(number: str, table: dict[str, object]) -> Document:
    """Build a :class:`Document` from one TOML table.

    Args:
        number: Table name in ``documents.toml``.
        table: Parsed table.

    Returns:
        The document.

    Raises:
        ValueError: If a field is missing, malformed, or inconsistent.
    """
    if NUMBER_PATTERN.match(number) is None:
        raise ValueError(f"Document number '{number}' must have the form YYYY-NNN.")
    status = _require_string(number, table, "status", required=True)
    if status not in VALID_STATUSES:
        raise ValueError(f"Document '{number}' has an invalid status '{status}'; expected one of {VALID_STATUSES}.")
    slug = _require_string(number, table, "slug", required=status == STATUS_ACTIVE)
    if slug and SLUG_PATTERN.match(slug) is None:
        raise ValueError(f"Document '{number}' has an invalid slug '{slug}'; expected snake_case ASCII.")
    return Document(
        number=number,
        slug=slug,
        title=_require_string(number, table, "title", required=True),
        status=status,
        author=_require_string(number, table, "author", required=False, default=DEFAULT_AUTHOR),
        note=_require_string(number, table, "note", required=False),
    )


def load_documents(path: Path = DOCUMENTS_PATH) -> tuple[Document, ...]:
    """Read the document registry.

    Args:
        path: Path to ``documents.toml``.

    Returns:
        The documents sorted by number.

    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is malformed or two documents share a slug.
    """
    with path.open("rb") as stream:
        data = tomllib.load(stream)
    tables = data.get("documents")
    if not isinstance(tables, dict):
        raise ValueError(f"Registry '{path}' must define a [documents] table.")
    documents = sorted((_parse_document(number, table) for number, table in tables.items()), key=_number_key)
    slugs = [document.slug for document in documents if document.slug]
    duplicates = sorted({slug for slug in slugs if slugs.count(slug) > 1})
    if duplicates:
        raise ValueError(f"Registry '{path}' uses a slug more than once: {', '.join(duplicates)}.")
    return tuple(documents)


def _number_key(document: Document) -> tuple[int, int]:
    """Return the sort key of a document: year, then serial number."""
    match = NUMBER_PATTERN.match(document.number)
    assert match is not None
    return int(match["year"]), int(match["serial"])


def next_number(documents: Iterable[Document], year: int) -> str:
    """Return the next free number of a year.

    Withdrawn documents keep their numbers, so they are counted.

    Args:
        documents: Registered documents.
        year: Year in which the number is assigned.

    Returns:
        The next number ``YYYY-001``, ``YYYY-002``, and so on.

    Raises:
        ValueError: If the year has no free serial number left.
    """
    serials = [_number_key(document)[1] for document in documents if _number_key(document)[0] == year]
    return format_number(year, max(serials, default=0) + 1)


def number_for_topic(slug: str, documents: Iterable[Document]) -> str:
    """Return the number of the active document of a topic.

    Args:
        slug: Topic directory name.
        documents: Registered documents.

    Returns:
        The document number.

    Raises:
        KeyError: If no active document has this slug.
    """
    for document in documents:
        if document.slug == slug and document.status == STATUS_ACTIVE:
            return document.number
    raise KeyError(f"Topic '{slug}' has no active document number in documents.toml.")


def render_bibtex(documents: Iterable[Document]) -> str:
    """Render the documents as a BibTeX database.

    Args:
        documents: Registered documents.

    Returns:
        The BibTeX text, ending with a newline.
    """
    entries = [BIB_HEADER]
    for document in documents:
        year = int(document.number.split("-")[0])
        lines = [
            f"@report{{{document.number},",
            f"  author      = {{{document.author}}},",
            f"  title       = {{{document.title}}},",
            f"  type        = {{{BIB_TYPE_LABEL}}},",
            f"  number      = {{{document.number}}},",
            f"  institution = {{{INSTITUTION}}},",
            f"  year        = {{{year}}},",
        ]
        if document.note:
            lines.append(f"  note        = {{{document.note}}},")
        lines.append("}")
        entries.append("\n".join(lines) + "\n")
    return "\n".join(entries)


def find_latex_citations(text: str) -> list[tuple[int, str]]:
    """Find the document numbers cited with ``\\cite`` commands in LaTeX text.

    Args:
        text: LaTeX source. Comment lines are skipped.

    Returns:
        One ``(line_number, number)`` tuple per citation, in line order.
    """
    found: list[tuple[int, str]] = []
    for line_number, line in enumerate(text.splitlines(), start=1):
        if line.lstrip().startswith(LATEX_COMMENT_PREFIX):
            continue
        for match in LATEX_CITE_PATTERN.finditer(line):
            for key in match.group(1).split(","):
                if NUMBER_PATTERN.match(key.strip()):
                    found.append((line_number, key.strip()))
    return found


def find_notebook_citations(text: str) -> list[tuple[int, str]]:
    """Find the document numbers cited as ``[YYYY-NNN]`` or ``[YYYY-NNN, Sec. 3]`` in notebook text.

    Args:
        text: Content of a notebook ``.py`` file.

    Returns:
        One ``(line_number, number)`` tuple per citation, in line order.
    """
    return [
        (line_number, match.group(1))
        for line_number, line in enumerate(text.splitlines(), start=1)
        for match in NOTEBOOK_CITE_PATTERN.finditer(line)
    ]


def _check_topics(documents: Sequence[Document], topics_dir: Path) -> list[str]:
    """Check that topics and active documents correspond one to one.

    Args:
        documents: Registered documents.
        topics_dir: Directory holding one subdirectory per topic.

    Returns:
        The problems found.
    """
    problems: list[str] = []
    active_slugs = {document.slug for document in documents if document.status == STATUS_ACTIVE}
    for latex_path in sorted(topics_dir.glob(f"*/{LATEX_FILE_NAME}")):
        if latex_path.parent.name not in active_slugs:
            problems.append(f"Topic '{latex_path.parent.name}' has no active document number in documents.toml.")
    for document in documents:
        if document.status != STATUS_ACTIVE:
            continue
        topic_dir = topics_dir / document.slug
        latex_path = topic_dir / LATEX_FILE_NAME
        notebook_path = topic_dir / f"{document.slug}.py"
        if not latex_path.is_file():
            problems.append(f"Document {document.number}: {latex_path} does not exist.")
            continue
        numbers = LATEX_NUMBER_MACRO_PATTERN.findall(latex_path.read_text(encoding="utf-8"))
        if numbers != [document.number]:
            problems.append(
                f"Document {document.number}: {latex_path} must contain exactly one "
                f"\\setmemonumber{{{document.number}}}, found {numbers}."
            )
        if notebook_path.is_file() and f"Memo {document.number}" not in notebook_path.read_text(encoding="utf-8"):
            problems.append(f"Document {document.number}: {notebook_path} must mention 'Memo {document.number}'.")
    return problems


def _check_citations(documents: Sequence[Document], topics_dir: Path) -> list[str]:
    """Check that every cited document number is registered and active.

    Args:
        documents: Registered documents.
        topics_dir: Directory holding one subdirectory per topic.

    Returns:
        The problems found.
    """
    status_of = {document.number: document.status for document in documents}
    sources = [(path, find_latex_citations) for path in sorted(topics_dir.glob(f"*/{LATEX_FILE_NAME}"))]
    sources += [(path, find_notebook_citations) for path in sorted(topics_dir.glob("*/*.py"))]
    problems: list[str] = []
    for path, finder in sources:
        for line_number, number in finder(path.read_text(encoding="utf-8")):
            if number not in status_of:
                problems.append(f"{path}:{line_number}: cites unregistered document {number}.")
            elif status_of[number] != STATUS_ACTIVE:
                problems.append(f"{path}:{line_number}: cites withdrawn document {number}.")
    return problems


def check_repository(
    documents_path: Path = DOCUMENTS_PATH,
    bib_path: Path = DOCUMENTS_BIB_PATH,
    topics_dir: Path = TOPICS_DIR,
) -> list[str]:
    """Check the repository against the document registry.

    Args:
        documents_path: Path to ``documents.toml``.
        bib_path: Path to the generated ``documents.bib``.
        topics_dir: Directory holding one subdirectory per topic.

    Returns:
        The problems found. An empty list means the repository is consistent.
    """
    documents = load_documents(documents_path)
    problems = _check_topics(documents, topics_dir)
    problems += _check_citations(documents, topics_dir)
    if not bib_path.is_file() or bib_path.read_text(encoding="utf-8") != render_bibtex(documents):
        problems.append(f"{bib_path} is out of date; run documents.py --write.")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    """Check the repository, regenerate the BibTeX database, or print a number.

    Args:
        argv: Argument list without the program name. ``None`` reads ``sys.argv``.

    Returns:
        Process exit code: 0 on success, 1 when a problem is found or a topic is not registered.
    """
    parser = argparse.ArgumentParser(description="Check and use the document numbers of the topics.")
    parser.add_argument("--write", action="store_true", help="Regenerate common/documents.bib.")
    parser.add_argument("--number", metavar="TOPIC", help="Print the document number of a topic.")
    parser.add_argument("--next", action="store_true", help="Print the next free number of the year.")
    parser.add_argument("--year", type=int, default=datetime.date.today().year, help="Year for --next.")
    args = parser.parse_args(argv)
    documents = load_documents()
    if args.write:
        DOCUMENTS_BIB_PATH.write_text(render_bibtex(documents), encoding="utf-8")
        print(f"Wrote {DOCUMENTS_BIB_PATH}")
        return 0
    if args.number:
        try:
            print(number_for_topic(args.number, documents))
        except KeyError as exc:
            print(exc.args[0], file=sys.stderr)
            return 1
        return 0
    if args.next:
        print(next_number(documents, args.year))
        return 0
    problems = check_repository()
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
