"""Load the Japanese terminology glossary and check LaTeX sources against it.

The glossary lives in ``common/glossary.toml`` and is the single source of truth for the Japanese
translation of technical terms. This module reads it, reports forbidden Japanese forms found in a
LaTeX source, and renders the human-readable index ``common/glossary.md``.

Usage (from the repository root)::

    python common/python/dynamics_common/glossary.py --write
"""

import argparse
import sys
import tomllib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
GLOSSARY_PATH = REPO_ROOT / "common" / "glossary.toml"
GLOSSARY_MARKDOWN_PATH = REPO_ROOT / "common" / "glossary.md"
TOPICS_DIR = REPO_ROOT / "topics"
LATEX_SUFFIX = ".tex"
LATEX_COMMENT_PREFIX = "%"
MARKDOWN_HEADER = """# Glossary

Generated from [glossary.toml](glossary.toml) by `python common/python/dynamics_common/glossary.py --write`.
Do not edit this file by hand; edit `glossary.toml` and regenerate.

The Japanese column is the preferred translation. The forbidden column lists forms that must not be
used; `common/python/tests/test_topics_glossary.py` fails when one of them appears in a topic's
`main.tex`.
"""

__all__ = [
    "GLOSSARY_MARKDOWN_PATH",
    "GLOSSARY_PATH",
    "GlossaryTerm",
    "Violation",
    "find_forbidden_terms",
    "load_glossary",
    "render_markdown",
    "scan_latex_file",
]


@dataclass(frozen=True)
class GlossaryTerm:
    """One glossary entry.

    Attributes:
        key: Term identifier, the table name in ``glossary.toml``.
        en: English term.
        ja: Preferred Japanese translation.
        forbidden_ja: Japanese forms that must not be used.
        note: Reason for the choice, or a usage restriction.
    """

    key: str
    en: str
    ja: str
    forbidden_ja: tuple[str, ...] = ()
    note: str = ""


@dataclass(frozen=True)
class Violation:
    """A forbidden Japanese form found in a source file.

    Attributes:
        path: Source file.
        line_number: One-based line number.
        term_key: Glossary key of the violated term.
        forbidden: The forbidden form that was found.
        line: The offending source line, stripped.
    """

    path: Path
    line_number: int
    term_key: str
    forbidden: str
    line: str


def _parse_term(key: str, table: dict[str, object]) -> GlossaryTerm:
    """Build a :class:`GlossaryTerm` from one TOML table.

    Args:
        key: Table name in ``glossary.toml``.
        table: Parsed table.

    Returns:
        The glossary term.

    Raises:
        ValueError: If a required field is missing or has the wrong type.
    """
    en = table.get("en")
    ja = table.get("ja")
    if not isinstance(en, str) or not en:
        raise ValueError(f"Term '{key}' must define a non-empty string 'en'.")
    if not isinstance(ja, str) or not ja:
        raise ValueError(f"Term '{key}' must define a non-empty string 'ja'.")
    forbidden = table.get("forbidden_ja", [])
    if not isinstance(forbidden, list) or not all(isinstance(item, str) and item for item in forbidden):
        raise ValueError(f"Term '{key}' has an invalid 'forbidden_ja'; expected a list of non-empty strings.")
    note = table.get("note", "")
    if not isinstance(note, str):
        raise ValueError(f"Term '{key}' has an invalid 'note'; expected a string.")
    return GlossaryTerm(key=key, en=en, ja=ja, forbidden_ja=tuple(forbidden), note=note)


def load_glossary(path: Path = GLOSSARY_PATH) -> tuple[GlossaryTerm, ...]:
    """Read the glossary file.

    Args:
        path: Path to ``glossary.toml``.

    Returns:
        The terms sorted by key.

    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is malformed.
    """
    with path.open("rb") as stream:
        data = tomllib.load(stream)
    terms = data.get("terms")
    if not isinstance(terms, dict):
        raise ValueError(f"Glossary '{path}' must define a [terms] table.")
    parsed = [_parse_term(key, table) for key, table in terms.items()]
    return tuple(sorted(parsed, key=lambda term: term.key))


def find_forbidden_terms(text: str, terms: Iterable[GlossaryTerm]) -> list[tuple[int, GlossaryTerm, str]]:
    """Find forbidden Japanese forms in a text.

    Args:
        text: Source text, for example the content of a LaTeX file.
        terms: Glossary terms to check.

    Returns:
        One ``(line_number, term, forbidden)`` tuple per occurrence, in line order.
    """
    matches: list[tuple[int, GlossaryTerm, str]] = []
    for line_number, line in enumerate(text.splitlines(), start=1):
        for term in terms:
            for forbidden in term.forbidden_ja:
                if forbidden in line:
                    matches.append((line_number, term, forbidden))
    return matches


def scan_latex_file(path: Path, terms: Iterable[GlossaryTerm]) -> list[Violation]:
    """Scan a LaTeX file for forbidden Japanese forms, skipping comment lines.

    Args:
        path: LaTeX source file.
        terms: Glossary terms to check.

    Returns:
        The violations found, in line order.
    """
    text = path.read_text(encoding="utf-8")
    violations: list[Violation] = []
    for line_number, term, forbidden in find_forbidden_terms(text, terms):
        line = text.splitlines()[line_number - 1]
        if line.lstrip().startswith(LATEX_COMMENT_PREFIX):
            continue
        violations.append(
            Violation(
                path=path,
                line_number=line_number,
                term_key=term.key,
                forbidden=forbidden,
                line=line.strip(),
            )
        )
    return violations


def render_markdown(terms: Sequence[GlossaryTerm]) -> str:
    """Render the glossary as a Markdown index.

    Args:
        terms: Glossary terms.

    Returns:
        The Markdown document, ending with a newline.
    """
    lines = [
        MARKDOWN_HEADER,
        "| Key | English | Japanese | Forbidden | Note |",
        "|---|---|---|---|---|",
    ]
    for term in terms:
        forbidden = ", ".join(term.forbidden_ja) if term.forbidden_ja else "—"
        note = term.note if term.note else "—"
        lines.append(f"| `{term.key}` | {term.en} | {term.ja} | {forbidden} | {note} |")
    return "\n".join(lines) + "\n"


def _topic_latex_files(topics_dir: Path = TOPICS_DIR) -> list[Path]:
    """Return the LaTeX sources of all topics.

    Args:
        topics_dir: Directory holding one subdirectory per topic.

    Returns:
        The ``main.tex`` files, sorted.
    """
    return sorted(topics_dir.glob(f"*/main{LATEX_SUFFIX}"))


def main(argv: Sequence[str] | None = None) -> int:
    """Check the topic sources or regenerate the Markdown index.

    Args:
        argv: Argument list without the program name. ``None`` reads ``sys.argv``.

    Returns:
        Process exit code: 0 on success, 1 when a forbidden form is found.
    """
    parser = argparse.ArgumentParser(description="Check topic LaTeX sources against the Japanese glossary.")
    parser.add_argument("--write", action="store_true", help="Regenerate common/glossary.md.")
    args = parser.parse_args(argv)
    terms = load_glossary()
    if args.write:
        GLOSSARY_MARKDOWN_PATH.write_text(render_markdown(terms), encoding="utf-8")
        print(f"Wrote {GLOSSARY_MARKDOWN_PATH}")
        return 0
    violations = [violation for path in _topic_latex_files() for violation in scan_latex_file(path, terms)]
    for violation in violations:
        print(
            f"{violation.path}:{violation.line_number}: "
            f"forbidden '{violation.forbidden}' for term '{violation.term_key}'"
        )
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
