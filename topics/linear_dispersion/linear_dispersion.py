# ## 9. Summary and open points
#
# 1. The dispersion solves $D'' + (h^2+k)\,D = h$ with the entrance conditions $D_0$, $D'_0$. Its homogeneous part
#    propagates with the $(x, p_x)$ block of the transfer matrix, and the particular solution $D_p$ is the dispersion
#    generated by the element.
# 2. Drift space: $D = D_0 + L D'_0$, $D' = D'_0$. No dispersion is generated.
# 3. Sector dipole magnet: $D = \rho(1-\cos\theta) + D_0\cos\theta + \rho D'_0\sin\theta$. The bend generates
#    $\rho(1-\cos\theta)$ from zero.
# 4. Quadrupole magnet: $D = D_0\cos(gL) + (D'_0/g)\sin(gL)$ for $k > 0$ and the hyperbolic form for $k < 0$. No
#    dispersion is generated.
# 5. Off-momentum particles: $x = x_\beta + D\,\delta$. With $x_0 = p_{x0} = 0$ and $\delta_0 \neq 0$ the particle
#    follows the dispersive orbit $D(s)\,\delta_0$, not the reference orbit.
# 6. Finite betatron amplitude: $\partial\mathbf{P}/\partial\delta_0 = \mathbf{R}_{:,6} + \mathbf{A}\mathbf{u}_0$,
#    with $A_{ij} = \partial^2 w_i/\partial\delta_0\partial u_{0j}$. The drift space contributes only through
#    $p_{x0}$, $p_{y0}$, and $\delta_0$; the bend and the quadrupole contribute through the betatron amplitude as
#    well. The effective dispersion is $D_\mathrm{eff} = D + (\mathbf{A}\mathbf{u}_0)_1$.
