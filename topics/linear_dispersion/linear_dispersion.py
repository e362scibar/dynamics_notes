rng = np.random.default_rng(RNG_SEED)


def random_point(symbols: list) -> dict:
    """Random positive values for the parameters and random real values for the entrance dispersion."""
    values = {}
    for sym in symbols:
        if sym in (D0, Dp0):
            values[sym] = rng.uniform(-1.0, 1.0)
        else:
            values[sym] = rng.uniform(RANDOM_LOW, RANDOM_HIGH)
    return values


def max_residual(expr) -> float:
    """Largest absolute value of an expression over random points."""
    symbols = sorted(sp.sympify(expr).free_symbols, key=str)
    func = sp.lambdify(symbols, expr, "numpy")
    worst = 0.0
    for _ in range(N_RANDOM_POINTS):
        point = random_point(symbols)
        value = np.array(func(*[point[sym] for sym in symbols]), dtype=float)
        worst = max(worst, float(np.max(np.abs(value))))
    return worst


